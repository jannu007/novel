interface Ctx {
  title: string;
  genre: string;
  protagonist: string;
  deuteragonist: string | null;
  antagonist: string | null;
  synopsis: string;
  characters: Character[];
  plotPoints: PlotPoint[];
}

function tokensFor(ctx: Ctx): Record<string, string> {
  return {
    p: ctx.protagonist,
    g: ctx.genre ? `${ctx.genre}の` : '',
    d: ctx.deuteragonist ?? '大切な誰か',
    a: ctx.antagonist ?? '正体不明の相手',
    t: ctx.title,
  };
}

/**
 * つなぎ文は「述部（predicate、必ず。で終わる自己完結した一文）」に、
 * 3通りのいずれかで前置き句を組み合わせて作る：
 *   (1) 述部のみ
 *   (2) パート固有の情感句（mood、〜、で終わる）+ 述部
 *   (3) 汎用の場面転換句（OPENERS）+ 述部
 * 前置き句と述部を独立に選ぶことで、少ない手書き素材から桁違いに
 * 多い組み合わせ数を生み出す（例：mood30種×predicate30種＝900通り）。
 * まだ作品をまたいで使っていない候補を優先し、選んだテンプレート
 * （置換前の文字列）は usedThisRun に記録する。
 */
function makeFillerGenerator(
  rng: () => number,
  moodTemplates: string[],
  predicateTemplates: string[],
  ctx: Ctx,
  avoid: Set<string>,
  usedThisRun: Set<string>
) {
  const tokens = tokensFor(ctx);
  const moodPool = preferUnused(moodTemplates, avoid, (t) => t);
  const predicatePool = preferUnused(predicateTemplates, avoid, (t) => t);
  const openerPool = preferUnused(OPENERS, avoid, (t) => t);
  const nextMood = makeShuffleBag(rng, moodPool);
  const nextPredicate = makeShuffleBag(rng, predicatePool);
  const nextOpener = makeShuffleBag(rng, openerPool);
  return () => {
    const predicateTemplate = nextPredicate();
    usedThisRun.add(predicateTemplate);
    const predicate = ensurePeriod(fillTemplate(predicateTemplate, tokens));
    const roll = rng();
    if (roll < 0.34) {
      return predicate;
    }
    if (roll < 0.67) {
      const moodTemplate = nextMood();
      usedThisRun.add(moodTemplate);
      return `${fillTemplate(moodTemplate, tokens)}${predicate}`;
    }
    const openerTemplate = nextOpener();
    usedThisRun.add(openerTemplate);
    return `${fillTemplate(openerTemplate, tokens)}${predicate}`;
  };
}

/**
 * 文単位・段落単位で積み上げ、最低文字数(minChars)を必ず満たすまで
 * 生成し続ける。段落は改行区切りにする（空行を挟むと「＊」のシーン
 * 区切り記号になってしまうため、単一の改行のみを使う）。
 */
function assemble(
  sentences: string[],
  fillerGenerator: () => string,
  minChars = MIN_CHARS_PER_ACT,
  maxChars = MAX_CHARS_PER_ACT
): string {
  const paragraphs: string[] = [];
  let currentPara = '';
  let total = 0;

  function push(sentence: string) {
    currentPara += sentence;
    total += countChars(sentence);
    if (countChars(currentPara) >= PARAGRAPH_TARGET) {
      paragraphs.push(currentPara);
      currentPara = '';
    }
  }

  const pool = [...sentences];
  while (pool.length > 0 && total < maxChars) {
    push(ensurePeriod(pool.shift()!));
  }

  let lastSentence = '';
  let guard = 0;
  while (total < minChars && guard < 400) {
    guard++;
    let s = fillerGenerator();
    let attempts = 0;
    while (s === lastSentence && attempts < 5) {
      s = fillerGenerator();
      attempts++;
    }
    lastSentence = s;
    push(s);
  }

  if (currentPara) paragraphs.push(currentPara);
  return paragraphs.join('\n');
}

function buildCtx(novel: Novel): Ctx {
  const protagonistChar =
    novel.characters.find((c) => c.role === '主人公') ?? novel.characters[0];
  const deuteragonistChar = novel.characters.find(
    (c) => c.role === 'ヒロイン' && c !== protagonistChar
  ) ?? novel.characters.find((c) => c !== protagonistChar && c.role !== '敵役');
  const antagonistChar = novel.characters.find((c) => c.role === '敵役');
  // 主人公キャラクターが未登録でも、本文の主語が「主人公」という
  // 一般名詞のままにならないよう、作品ごとに決定的な人名を割り当てる。
  const protagonist = protagonistChar?.name || fallbackName(`${novel.id}:protagonist`);
  return {
    title: novel.title || '無題の物語',
    genre: novel.genre.trim(),
    protagonist,
    deuteragonist: deuteragonistChar?.name || null,
    antagonist: antagonistChar?.name || null,
    synopsis: novel.synopsis.trim(),
    characters: novel.characters,
    plotPoints: novel.plotPoints,
  };
}

